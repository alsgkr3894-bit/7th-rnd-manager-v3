export function buildNoteCardGridProps({
  visible,
  filtered,
  sortBy,
  canEdit = false,
  batchMode,
  selected,
  pinnedIds,
  popIds,
  hlRe,
  openContextMenu,
  onOpenDetail,
  onEditNote,
  onToggleSelect,
  onTogglePin,
  onCopy,
  onDelete,
  onStatusChange,
  onTypeChange,
  onNewVersion,
  onTagClick,
  onDropMerge,
  onUnmergeGroup,
  onLoadMore,
}) {
  return {
    visible,
    filtered,
    sortBy,
    filteredCount: filtered.length,
    canEdit,
    batchMode,
    selected,
    pinnedIds,
    popIds,
    hlRe,
    onContextMenu: openContextMenu,
    onToggleSelect,
    onOpen: onOpenDetail,
    onEdit: (note, event) => {
      event?.stopPropagation();
      if (canEdit) onEditNote(note);
    },
    onDelete,
    onCopy,
    onStatusChange,
    onTypeChange,
    onNewVersion,
    onPin: onTogglePin,
    onTagClick,
    onDropMerge,
    onUnmergeGroup,
    onLoadMore,
  };
}

