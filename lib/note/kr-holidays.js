/** @param {string} dateKey - 'YYYY-MM-DD' */
export function getKrHolidayName(dateKey) {
  const key = String(dateKey || '');
  if (key.length < 10) return null;
  const year = key.slice(0, 4);
  const monthDay = key.slice(5, 10);
  return KR_HOLIDAYS[year]?.[monthDay] || null;
}

export function isKrHoliday(dateKey) {
  return Boolean(getKrHolidayName(dateKey));
}
